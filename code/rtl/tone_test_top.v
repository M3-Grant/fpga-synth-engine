// ============================================================================
//  模块名  : tone_test_top.v
//  作用    : 【生死线验证工程】上板后耳机里应该立刻听到一个持续的单音
//            这是整个项目第一个必须打通的关卡 —— 有声音，方案成立；
//            没声音，先别往下做，先把 I2S 调通。
//
//  板卡    : Sipeed Tang Nano 20K (GW2AR-LV18QN88C8/I7)，主时钟 27 MHz
//  引脚    : clk=4, i2s_din=54, i2s_lrck=55, i2s_bck=56, pa_en=51（取自官方 audio 例程）
//
//  ── 好消息：板载已有一片 I2S DAC（MAX98357A）──────────────────────
//    原理图确认：PIN54→I2S_DIN, PIN55→I2S_LRCK, PIN56→I2S_BCLK, PIN51→PA_SD/EN
//    输出经 J4（2pin 座子）接 4~8Ω 喇叭。
//    MAX98357A 无需 MCLK，支持 8k~96kHz，正好兼容我们的 52.734kHz。
//    → 所以"生死线"可以**完全不接线**，只要把 pa_en 拉高、喇叭插 J4 就能响。
//    ⚠️ 但它是单声道（SD_MODE>1.4V 时只出左声道）+ D 类功放，底噪大，
//       做频谱验证和最终演示还是要外接 PCM5102A。
//
//  原理    : 32 位相位累加器每个音频样本加一次 FCW，
//            取累加器最高位当方波输出 → 频率 = FCW × fs / 2^32，非常准。
//            用方波是因为它不需要波形 ROM，第一天最容易出声。
//
//  ⚠️ 关键：fs 不是 48000，是 52734.375（27MHz / 8 / 64）
//           所以 FCW 必须按 52734.375 算，用 48000 算会跑调两个半音！
//
//  常用 FCW（fs = 52734.375 Hz，由 tools/gen_fcw.py 生成）：
//      C4 261.63Hz = 32'd21308174
//      D4 293.66Hz = 32'd23917617
//      E4 329.63Hz = 32'd26846617
//      F4 349.23Hz = 32'd28443000
//      G4 391.99Hz = 32'd31926188
//      A4 440.00Hz = 32'd35835935   ← 默认
//      B4 493.88Hz = 32'd40224476
//      C5 523.25Hz = 32'd42616348
// ============================================================================
module tone_test_top #(
    parameter FCW      = 32'd35835935,  // A4 = 440 Hz
    parameter BCK_HALF = 4,             // BCK = 27MHz/8 = 3.375MHz → fs = 52734.375Hz
    parameter AMP      = 16'sh2000      // 幅度 = 1/4 满量程，避免刺耳
)(
    input  wire        clk,        // 27 MHz，引脚 4
    output wire        i2s_bck,    // 位时钟，引脚 56
    output wire        i2s_lrck,   // 声道时钟，引脚 55
    output wire        i2s_din,    // 串行数据，引脚 54
    output wire        pa_en,      // 板载功放使能，引脚 51，拉高=开
    output wire [5:0]  led         // 板载 LED，低电平点亮
);

    // ------------------------------------------------------------------
    // 1. 上电复位：不依赖外部按键，省掉一类入门坑
    //    27MHz 下 2^16 个周期 ≈ 2.4 ms，足够长
    // ------------------------------------------------------------------
    reg [15:0] por_cnt = 16'd0;
    reg        rst_n   = 1'b0;

    always @(posedge clk) begin
        if (&por_cnt) rst_n <= 1'b1;
        else          por_cnt <= por_cnt + 16'd1;
    end

    // ------------------------------------------------------------------
    // 2. 相位累加器：每个音频样本加一次 FCW
    //    ⚠️ sample_req 必须先声明再使用（iverilog v14 和 Gowin 综合都要求这一点，
    //       v12 会放过，v14 会报 "Check for declaration after use"）
    // ------------------------------------------------------------------
    wire        sample_req;
    reg  [31:0] phase = 32'd0;

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) phase <= 32'd0;
        else if (sample_req) phase <= phase + FCW;
    end

    // ------------------------------------------------------------------
    // 3. 方波：直接取相位最高位（左右声道同相，方便测）
    // ------------------------------------------------------------------
    wire [15:0] sample = phase[31] ? AMP : -AMP;

    // ------------------------------------------------------------------
    // 4. I2S 发送（sample_req 已在第 2 节声明）
    // ------------------------------------------------------------------
    i2s_tx #(.DATA_BITS(16), .BCK_HALF(BCK_HALF)) u_i2s (
        .clk        (clk),
        .rst_n      (rst_n),
        .sample_l   (sample),
        .sample_r   (sample),
        .bck        (i2s_bck),
        .lrck       (i2s_lrck),
        .din        (i2s_din),
        .sample_req (sample_req)
    );

    // ------------------------------------------------------------------
    // 5. LED 指示：led[0] 约 1.6 Hz 闪烁，证明逻辑在跑
    //    （板载 LED 低电平点亮，所以要取反）
    // ------------------------------------------------------------------
    reg [23:0] blink = 24'd0;
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) blink <= 24'd0;
        else        blink <= blink + 24'd1;
    end

    assign led = ~{5'b00000, blink[23]};

    // ------------------------------------------------------------------
    // 6. 板载功放使能：常开
    //    SD_MODE > 1.4V → 只输出左声道（本工程左右同数据，无影响）
    //    不想用板载喇叭时把这个改成 1'b0 即可
    // ------------------------------------------------------------------
    assign pa_en = 1'b1;

endmodule
