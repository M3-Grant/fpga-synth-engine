// ============================================================================
//  模块名  : osc_voice.v
//  功能    : 单个振荡器声部 —— DDS 相位累加器 + 方波输出 + 包络调制入口
//  板卡    : Sipeed Tang Nano 20K (GW2AR-18)，主时钟 27 MHz
//
//  ── 设计说明 ──────────────────────────────────────────────────────
//  这是"复音合成器"的最小发声单元。VOICE_NUM 份本模块并行工作，
//  每个声部独立跟踪自己的相位、频率与包络，实现真正的同时发声。
//
//  频率关系（DDS 标准公式）：
//      f_out = fcw × fs / 2^PHASE_BITS
//  其中 fs 为音频采样率（本项目 52734.375 Hz，见 gen_fcw.py）。
//
//  ── 关于波形 ──────────────────────────────────────────────────────
//  四种波形全部由相位直接算出，不需要波形 ROM，资源极省，
//  由 wave_sel[1:0] 运行时切换（组合逻辑，切换无延迟）：
//      2'b00 三角波（默认）   2'b01 方波
//      2'b10 锯齿波           2'b11 脉冲波 25%
//  四种波形峰值都等于 AMP，切换不会引起音量突变。
//  这个接口是为"第二交互维度"（红外手势切换音色）预留的。
//
//  ── 关于包络 ──────────────────────────────────────────────────────
//  env 为 0~255 的包络电平，与方波样本相乘后输出。
//  乘法用移位相加实现（每周期乘 1/8，8 个周期完成），
//  避免占用 DSP 乘法器 —— 48 个 DSP 不够 32 个声部各用一个。
//
//  作者    : 第二代迭代 1
// ============================================================================
module osc_voice #(
    parameter PHASE_BITS = 32,          // 相位累加器位宽
    parameter AMP        = 16'sh2000    // 基础幅度（有符号）
)(
    input  wire                  clk,
    input  wire                  rst_n,
    input  wire                  sample_en,   // 音频采样使能（每帧 1 个 clk）
    input  wire [PHASE_BITS-1:0] fcw,         // 频率控制字
    input  wire [7:0]            env,         // 包络电平 0~255（255 = 满幅）
    input  wire                  gate,        // 1 = 发声，0 = 静音
    input  wire [1:0]            wave_sel,    // 波形选择，见下方"波形生成"段
    output reg  signed [15:0]    sample       // 有符号音频样本
);

    // ------------------------------------------------------------------
    // 1. 相位累加器：每个采样周期加一次 FCW，自然溢出即回绕
    // ------------------------------------------------------------------
    reg [PHASE_BITS-1:0] phase;

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            phase <= {PHASE_BITS{1'b0}};
        end
        else if (sample_en) begin
            phase <= phase + fcw;
        end
    end

    // ------------------------------------------------------------------
    // 2. 波形生成
    //    WAVE_TRI = 0 → 方波：奇次谐波按 1/n   衰减，明亮但偏"脏"
    //    WAVE_TRI = 1 → 三角波：奇次谐波按 1/n² 衰减，柔和干净得多
    //                   （3 次谐波比方波低 9.5dB，5 次低 14dB，9 次低 19dB）
    //    实测依据：2026-10-15 手机频谱显示方波能量一直拖到 10kHz 以上
    // ------------------------------------------------------------------
    // ------------------------------------------------------------------
    // 2. 波形生成 —— 四种波形全部从相位直接算出，不需要波形 ROM
    //      2'b00 三角波：奇次谐波按 1/n² 衰减 —— 柔和圆润（默认）
    //      2'b01 方波  ：奇次谐波按 1/n  衰减 —— 明亮有力，偏"脏"
    //      2'b10 锯齿波：全部谐波按 1/n  衰减 —— 比方波更饱满（含偶次谐波）
    //      2'b11 脉冲波：25% 占空比          —— 薄而带鼻音感
    //    ⚠️ 变量名不能叫 tri —— tri 是 Verilog 内置线网类型（三态线网）的关键字
    //    ⚠️ AMP 是编译期常数，× AMP 会被综合器展开成移位加法，不占 DSP 乘法器
    //    四种波形的峰值都等于 AMP，切换时不会剧变音量
    // ------------------------------------------------------------------

    wire [15:0] u = phase[PHASE_BITS-1:PHASE_BITS-16];   // 相位高 16 位

    // ---- 方波：取相位最高位 ----
    wire signed [15:0] w_sqr = phase[PHASE_BITS-1] ? AMP : -AMP;

    // ---- 三角波：把 u 折叠一次，得到 0→32767→0 ----
    //   tri_u = u[15] ? ~u : u      0 ~ 32767 ~ 0
    //   tri_c = tri_u - 16384      -16384 ~ +16383    （居中）
    //   tri_m = tri_c × AMP        ±16384 × AMP
    //   w_tri = tri_m >>> 14       ±AMP
    wire [15:0]        tri_u = u[15] ? ~u : u;
    wire signed [16:0] tri_c = {1'b0, tri_u} - 17'sd16384;
    wire signed [32:0] tri_m = tri_c * $signed({1'b0, AMP});
    // 位选 [29:14] 等价于 (tri_m >>> 14) 取低 16 位；显式位选可消除 Gowin EX3791 截断告警
    wire signed [15:0] w_tri = tri_m[29:14];

    // ---- 锯齿波：u 直接居中 ----
    //   saw_c = u - 32768          -32768 ~ +32767
    //   saw_m = saw_c × AMP        ±32768 × AMP
    //   w_saw = saw_m >>> 15       ±AMP
    wire signed [16:0] saw_c = {1'b0, u} - 17'sd32768;
    wire signed [32:0] saw_m = saw_c * $signed({1'b0, AMP});
    wire signed [15:0] w_saw = saw_m[30:15];

    // ---- 脉冲波：相位最高两位为 0 时输出高电平，占空比 25% ----
    wire signed [15:0] w_pls = (phase[PHASE_BITS-1:PHASE_BITS-2] == 2'b00) ? AMP : -AMP;

    // ---- 波形选择（组合逻辑，切换无延迟）----
    reg signed [15:0] wave;
    always @(*) begin
        case (wave_sel)
            2'b00:   wave = w_tri;
            2'b01:   wave = w_sqr;
            2'b10:   wave = w_saw;
            default: wave = w_pls;
        endcase
    end

    // ------------------------------------------------------------------
    // 3. 包络调制：sample = wave × env / 255
    //    用"先乘 env+1 再右移 8 位"近似，误差 < 0.4%，听感无差别
    // ------------------------------------------------------------------
    wire signed [23:0] env_ext  = {{8{wave[15]}}, wave};   // 符号扩展
    wire signed [23:0] env_gain = $signed({1'b0, env}) + 24'sd1;  // 1~256

    // 24×9 位的乘法交给综合器（它会用少量 LUT 实现，不抢 DSP）
    wire signed [32:0] modulated = env_ext * env_gain;

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            sample <= 16'sd0;
        end
        else if (sample_en) begin
            if (gate) begin
                // 显式取 [23:8] 而非 modulated >>> 8：
                // 33 位算术右移 8 位后赋给 16 位，等价于取低 16 位 = modulated[23:8]。
                // 写成位选是为了消除 Gowin 综合告警 EX3791（按位宽 25→16 判截断）。
                // 值域校核：AMP=8192, env_gain∈[1,256] → |modulated| ≤ 2097152 = 2^21，
                //           >>>8 后 |结果| ≤ 8192，16 位有符号(±32767)足够，无溢出。
                sample <= modulated[23:8];
            end
            else begin
                sample <= 16'sd0;
            end
        end
    end

endmodule
